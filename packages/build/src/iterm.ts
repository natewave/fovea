export const itermOutputs = (): readonly Output[] => [
  ...variants.map((v) => ({ path: itermYamlPath(v), contents: itermYaml(v) })),
  { path: `${ITERM_DIR}/PULL_REQUEST.md`, contents: pullRequest() },
  { path: `${ITERM_DIR}/README.md`, contents: itermReadme() },
];
