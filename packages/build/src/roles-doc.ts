import { FAMILIES, families, ROLE_NAMES, role, roles, variants } from "@fovea/palette";
import { ANSI_NAMES } from "@fovea/palette/audit";
import { formatTable } from "./markdown.ts";

const code = (text: string): string => `\`${text}\``;

const roleTable = (): string =>
  formatTable(
    ["Role", "Palette entry", ...variants.map((v) => v.name)],
    ROLE_NAMES.map((r) => [code(r), code(roles[r]), ...variants.map((v) => code(role(v, r)))]),
  );

const ansiTable = (): string =>
  formatTable(
    ["ANSI", "Name", ...variants.map((v) => v.name)],
    ANSI_NAMES.map((name, i) => [String(i), name, ...variants.map((v) => code(v.ansi[i] ?? ""))]),
    ["right", "left", ...variants.map(() => "left" as const)],
  );

const familyTable = (): string =>
  formatTable(
    ["Family", "Name", "OKLCH hue"],
    FAMILIES.map((f) => [code(f), families[f].name, `${families[f].hue}°`]),
    ["left", "left", "right"],
  );

/** The role-to-color tables that docs/style-guide.md points porters to. */
export const rolesReport = (): string =>
  [
    "<!-- Generated by packages/build from packages/palette. Do not edit. -->",
    "",
    "# Fovea roles",
    "",
    "Every role, the palette entry it points to, and its value in each variant. Ports map their",
    "colors to roles; the [style guide](../style-guide.md) explains how. Overlay roles are",
    "translucent `#rrggbbaa` colors meant to be drawn over `surface.editor`; `fovea.json` also",
    "lists each overlay's composited, opaque surface for apps that can't blend.",
    "",
    roleTable(),
    "",
    "## Terminal colors",
    "",
    "Identical in every terminal port.",
    "",
    ansiTable(),
    "",
    "## Hue families",
    "",
    "A family keeps its hue in every variant; only lightness and chroma change.",
    "",
    familyTable(),
    "",
  ].join("\n");
