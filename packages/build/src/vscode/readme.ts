import { apcaLc, wcagContrast } from "@fovea/colorlab";
import { CONTRAST_LABEL, role, type Variant } from "@fovea/palette";
import {
  bracketColorSettings,
  editorClis,
  italicSettings,
  marketplaceCommand,
  nightSetting,
  recommendedSettings,
  settingsJson,
  themeNames,
  vscodeSourceSteps,
} from "../install.ts";
import { fence, formatTable } from "../markdown.ts";
import { isPlaceholder, project, rawUrl, releasesUrl } from "../project.ts";

const shortName = (v: Variant): string => v.name.replace(/^Fovea /, "");

/** Text contrast of a variant's plain text on its editor background. */
export const textContrast = (v: Variant): string => {
  const text = role(v, "text");
  const surface = role(v, "surface.editor");
  return `Lc ${apcaLc({ text, surface }).toFixed(0)} · ${wcagContrast(text, surface).toFixed(1)}:1`;
};

const docs = {
  themes: "https://code.visualstudio.com/docs/configure/themes",
  vsix: "https://code.visualstudio.com/docs/configure/extensions/extension-marketplace#_install-from-a-vsix",
};

