export const NONE = "transparent";

/**
 * How one workbench color derives from the palette: a role, a palette entry (only where VS Code
 * asks for a hue by name), a role at reduced opacity, a choice per polarity, or nothing.
 */
export type ColorSpec =
  | Role
  | { readonly ref: Ref }
  | { readonly fade: Role | { readonly ref: Ref }; readonly alpha: number }
  | { readonly light: ColorSpec; readonly dark: ColorSpec }
  | typeof NONE;

const hue = (ref: Ref): ColorSpec => ({ ref });
const fade = (of: Role, alpha: number): ColorSpec => ({ fade: of, alpha });
const fadeHue = (ref: Ref, alpha: number): ColorSpec => ({ fade: { ref }, alpha });

/** Shadows darken in both polarities: warm ink on paper, the deepest surface in the dark. */
const SHADOW: ColorSpec = { light: fade("text.strong", 0.16), dark: "surface.chrome" };
/**
 * Find results are amber, the hue of the find overlays, so they never read as warnings. On paper
 * the mid tone is too light to outline the amber highlight at 3:1, so Day uses the text tone.
 */
const FIND_MARK: ColorSpec = { light: hue("orange.fg"), dark: hue("orange.dim") };
const SCROLL_SLIDER = fade("text.muted", 0.25);
const SCROLL_SLIDER_HOVER = fade("text.muted", 0.4);
const SCROLL_SLIDER_ACTIVE = fade("text.muted", 0.55);

const repeat = (prefix: string, count: number, spec: ColorSpec): Record<string, ColorSpec> =>
  Object.fromEntries(Array.from({ length: count }, (_, i) => [`${prefix}${i + 1}`, spec]));

