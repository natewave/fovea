const base = (v: Variant, of: Role | { readonly ref: Ref }): Hex =>
  typeof of === "string" ? role(v, of) : resolveRef(v, of.ref);

/** The hex value a spec takes in a variant. */
export const resolveSpec = (v: Variant, spec: ColorSpec): Hex => {
  if (spec === NONE) return withAlpha(v.neutral.bg, 0);
  if (typeof spec === "string") return role(v, spec);
  if ("ref" in spec) return resolveRef(v, spec.ref);
  if ("fade" in spec) return withAlpha(base(v, spec.fade), spec.alpha);
  return resolveSpec(v, v.polarity === "light" ? spec.light : spec.dark);
};

export const isTranslucent = (hex: Hex): boolean => parseHexAlpha(hex).alpha < 1;

/** Every workbench color in a variant, in the reference's order. */
export const resolveWorkbenchColors = (
  v: Variant,
  order: readonly string[],
): Readonly<Record<string, Hex>> =>
  Object.fromEntries(
    order.flatMap((key) => {
      const spec = workbenchColors[key];
      return spec === undefined ? [] : [[key, resolveSpec(v, spec)]];
    }),
  );
