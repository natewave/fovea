import type { Hex } from "@fovea/colorlab";
import { type Band, budget, CONTRAST_LABEL, type Variant } from "@fovea/palette";
import { formatTable } from "../markdown.ts";
import { codeSurfaceChecks, uiChecks } from "./audit.ts";
import { defaultedColors, workbenchColors } from "./colors.ts";
import { type ColorReference, referenceKeys } from "./reference.ts";

export interface Coverage {
  readonly set: readonly string[];
  readonly defaulted: readonly string[];
  /** In the reference but neither set nor deliberately left to the default. */
  readonly missing: readonly string[];
  /** Set or defaulted but not in the reference: typos, or keys VS Code removed. */
  readonly unknown: readonly string[];
  /** Both set and listed as defaulted. */
  readonly conflicting: readonly string[];
}

export const coverage = (reference: ColorReference): Coverage => {
  const keys = referenceKeys(reference);
  const known = new Set(keys);
  const set = Object.keys(workbenchColors);
  const defaulted = defaultedColors.flatMap((g) => g.keys);
  const isSet = new Set(set);
  const isDefaulted = new Set(defaulted);
  return {
    set: keys.filter((k) => isSet.has(k)),
    defaulted: keys.filter((k) => isDefaulted.has(k)),
    missing: keys.filter((k) => !isSet.has(k) && !isDefaulted.has(k)),
    unknown: [...set, ...defaulted].filter((k) => !known.has(k)),
    conflicting: set.filter((k) => isDefaulted.has(k)),
  };
};

const shortCommit = (commit: string): string => commit.slice(0, 7);

const docsUrl = (reference: ColorReference): string =>
  `https://github.com/microsoft/vscode-docs/blob/${reference.commit}/api/references/theme-color.md`;

const bandText = (band: Band): string => {
  const range = band.max === undefined ? `≥ ${band.min}` : `${band.min}–${band.max}`;
  return band.wcag === undefined ? range : `${range}, ${band.wcag}:1`;
};

const verdict = (lc: number, wcag: number, pass: boolean): string =>
  `${lc.toFixed(1)} · ${wcag.toFixed(2)}:1${pass ? "" : " ✕"}`;

const code = (text: string): string => `\`${text}\``;

/** `docs/generated/vscode-coverage.md`: which keys the theme sets, and how its UI text measures. */
export const coverageReport = (
  reference: ColorReference,
  variants: readonly Variant[],
  colors: (v: Variant) => Readonly<Record<string, Hex>>,
): string => {
  const c = coverage(reference);
  const isSet = new Set(c.set);
  const sectionRows = reference.sections.map((s) => {
    const set = s.keys.filter((k) => isSet.has(k.key)).length;
    return [s.name, String(s.keys.length), String(set), String(s.keys.length - set)];
  });
  const checks = variants.map((v) => uiChecks(v, colors(v)));
  const uiRows = checks[0]?.map((first, i) => [
    first.pair.label,
    `${code(first.pair.text)} on ${first.pair.on.map(code).join(" + ")}`,
    bandText(first.band),
    ...checks.map((vc) => {
      const check = vc[i];
      return check === undefined ? "" : verdict(check.lc, check.wcag, check.pass);
    }),
  ]);
  const surfaces = variants.map((v) => codeSurfaceChecks(v, colors(v)));
  const surfaceRows = surfaces[0]?.map((first, i) => [
    first.stack.slice(1).map(code).join(" + "),
    ...surfaces.map((vs) => {
      const check = vs[i];
      return check === undefined
        ? ""
        : `${verdict(check.lc, check.wcag, check.pass)} (${check.weakest})`;
    }),
  ]);
  const names = variants.map((v) => v.name.replace(/^Fovea /, ""));

  return [
    "<!-- Generated by `pnpm build` from packages/build/src/vscode/coverage.ts. Do not edit. -->",
    "",
    "# VS Code theme coverage",
    "",
    `Fovea's VS Code themes are checked against the [theme color reference](${docsUrl(reference)})`,
    `as of VS Code ${reference.vscodeVersion} (vscode-docs commit ${shortCommit(reference.commit)}),`,
    "pinned in [`fixtures/vscode/theme-color-keys.json`](../../fixtures/vscode/theme-color-keys.json).",
    "The mapping is in [`packages/build/src/vscode/colors.ts`](../../packages/build/src/vscode/colors.ts).",
    "",
    `- **Keys in the reference:** ${referenceKeys(reference).length}`,
    `- **Set by Fovea:** ${c.set.length}`,
    `- **Left to VS Code's defaults on purpose:** ${c.defaulted.length} (reasons below)`,
    `- **Neither:** ${c.missing.length}`,
    `- **Set but not in the reference:** ${c.unknown.length}`,
    "",
    "## By section",
    "",
    formatTable(["Section", "Keys", "Set", "Default"], sectionRows, [
      "left",
      "right",
      "right",
      "right",
    ]),
    "",
    "## Left to VS Code's defaults",
    "",
    ...defaultedColors.flatMap((g) => [
      `${g.reason}`,
      "",
      ...g.keys.map((k) => `- ${code(k)}`),
      "",
    ]),
    "## Contrast of workbench text and marks",
    "",
    `Each cell gives the ${CONTRAST_LABEL} and the WCAG 2.2 ratio of an element on the surface`,
    "VS Code paints it on. Translucent layers are flattened in order. The bands come from",
    "[`budget.ts`](../../packages/palette/src/budget.ts); ✕ marks a failure.",
    "",
    formatTable(["Element", "Keys", "Band", ...names], uiRows ?? []),
    "",
    "## Code on highlight backgrounds",
    "",
    "Backgrounds that code can sit on, beyond the palette overlays that",
    "[`docs/design.md`](../design.md) covers. Each cell is the token color with the lowest contrast",
    "there; every token color must reach the token-on-highlight band",
    `(${variants
      .map((v) => bandText(budget.onOverlay[v.id]))
      .filter((b, i, all) => all.indexOf(b) === i)
      .join(" / ")}).`,
    "",
    formatTable(["Background", ...names], surfaceRows ?? []),
    "",
  ].join("\n");
};
