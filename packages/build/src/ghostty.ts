import { type Variant, variants } from "@fovea/palette";
import {
  GHOSTTY_THEME_DIR,
  ghosttyConfigNote,
  ghosttyNightLine,
  ghosttySteps,
  ghosttyThemeLine,
  themeNames,
} from "./install.ts";
import { fence } from "./markdown.ts";
import type { Output } from "./output.ts";
import { project } from "./project.ts";
import { terminalColors } from "./terminal.ts";

export const GHOSTTY_DIR = "ports/ghostty";

/** Ghostty added the search colors in 1.3.0; older versions report them as unknown keys. */
export const GHOSTTY_MIN_VERSION = "1.3";

export type GhosttyEntry = readonly [key: string, value: string];

/** The theme's settings, in the order Ghostty's own theme files use. */
export const ghosttyEntries = (v: Variant): readonly GhosttyEntry[] => {
  const c = terminalColors(v);
  return [
    ...c.ansi.map((hex, i): GhosttyEntry => ["palette", `${i}=${hex}`]),
    ["background", c.background],
    ["foreground", c.foreground],
    ["cursor-color", c.cursor],
    ["cursor-text", c.cursorText],
    ["selection-background", c.selection],
    ["selection-foreground", c.selectionText],
    ["search-background", c.match],
    ["search-foreground", c.matchText],
    ["search-selected-background", c.currentMatch],
    ["search-selected-foreground", c.currentMatchText],
    ["split-divider-color", c.divider],
  ];
};

/** Ghostty names a theme after its file. */
export const ghosttyThemePath = (v: Variant): string => `${GHOSTTY_DIR}/themes/${v.name}`;

export const ghosttyTheme = (v: Variant): string =>
  [
    `# ${v.name}`,
    `# ${v.description}`,
    `# ${project.repository}`,
    "# Generated from packages/palette by packages/build. Do not edit.",
    "",
    ...ghosttyEntries(v).map(([key, value]) => `${key} = ${value}`),
    "",
  ].join("\n");

export const ghosttyReadme = (): string =>
  [
    "<!-- Generated by packages/build. Do not edit. -->",
    "",
    "# Fovea for Ghostty",
    "",
    `${themeNames.day}, ${themeNames.dusk} and ${themeNames.night} for [Ghostty](https://ghostty.org).`,
    `The themes need Ghostty ${GHOSTTY_MIN_VERSION} or later, which added the search colors they set.`,
    "",
    "## Install",
    "",
    `Copy the theme files into \`${GHOSTTY_THEME_DIR}\`:`,
    "",
    fence("sh", ghosttySteps.join("\n")),
    "",
    "Then add a theme line to your Ghostty config (`ghostty +edit-config` opens it). This one follows",
    "the system's light or dark appearance:",
    "",
    fence("", ghosttyThemeLine),
    "",
    `For dark rooms and late hours, use ${themeNames.night} as the dark theme:`,
    "",
    fence("", ghosttyNightLine),
    "",
    ghosttyConfigNote,
    "",
    "`ghostty +list-themes` should now list the three Fovea themes.",
    "",
    "## Settings that affect Fovea",
    "",
    "- `window-colorspace = srgb` is Ghostty's default and matches Fovea, which is designed in sRGB.",
    "  `display-p3` reads the same hex values in a wider color space, so colors look more saturated",
    "  than designed.",
    "- `minimum-contrast = 1` is the default and leaves Fovea's colors alone. Fovea's text colors",
    "  already meet its contrast budget; higher values make text more likely to become black or white.",
    "- `alpha-blending = linear-corrected` is optional. Ghostty describes it as removing the darkening",
    "  around text edges that some color pairs show, while keeping text weight close to `native`.",
    "  It is already the default outside macOS.",
    "- `palette-generate = true` is optional. It derives the 256-color palette's extra colors from",
    "  Fovea's 16 ANSI colors. Ghostty leaves it off by default because some programs assume the",
    "  standard xterm colors.",
    "",
    "## What the themes set",
    "",
    "The 16 ANSI colors, background, foreground, cursor, selection, search matches and split",
    "dividers. Selections and search matches use opaque versions of Fovea's overlays, with body text",
    "on top, so selected text stays readable whatever color a program printed it in. The ANSI colors",
    "match Fovea's VS Code themes exactly.",
    "",
  ].join("\n");

export const ghosttyOutputs = (): readonly Output[] => [
  ...variants.map((v) => ({ path: ghosttyThemePath(v), contents: ghosttyTheme(v) })),
  { path: `${GHOSTTY_DIR}/README.md`, contents: ghosttyReadme() },
];
